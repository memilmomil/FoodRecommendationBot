def josa(word: str, with_batchim: str, without_batchim: str) -> str:
    """마지막 글자 받침 유무에 따라 조사 선택 (이/가, 을/를 등)"""
    code = ord(word[-1]) - 0xAC00
    if 0 <= code <= 11171:
        return with_batchim if code % 28 else without_batchim
    return with_batchim


