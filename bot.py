async def recommend(interaction: discord.Interaction):
    main = random.choice(list(MENU))
    side = random.choice(MENU[main])
    dessert = random.choice(DESSERTS)
    snack = random.choice(SNACKS)

    msg = (
        f"🍚 저는 **{main}**{josa(main, '이', '가')} 좋을것같아요\n"
        f"🥗 사이드로 **{side}**\n"
        f"🍰 후식으로는 **{dessert}**{josa(dessert, '이', '가')} 좋을것같아요!\n"
        f"🍿 그리고 간식으로 **{snack}**{josa(snack, '을', '를')} 먹으면 딱 든든할것같아요!"
    )
    await interaction.response.send_message(msg)


